# Conversão de tipos, coerção
# Type convertion, typecasting, coercion
# É o ato de converter um tipo em outro
# Tipos imutáveis e primitivos
# str, int, float, bool

print (1 + 1.1)
# print("1" + 1)
print(int("1"), type(int("1"))) # Convertendo de str para int
print(float("10.10"), type(float("10.10"))) # Convertendo de str para float
print(bool(" "), type(bool(" "))) # Convertendo uma str para bool
print(str(11) + "b") # Convertendo um int para str 
