# Introdução a variáveis

# Variáveis são usadas para salvar algo na memória do computador.
# PEP8: Inicie suas variáveis com letras minúsculas, pode usar
# números e underline _.
# O sinal de = é o operador de atribuição. Ele é usado para 
# atribuir um valor a um nome (variável)
# Uso: nome_variável = expressão


full_name = "Carlos Eduardo Marques Veloso" # Definindo uma variável
age = 20
of_legal_age = age >= 18

print(f"Meu nome é {full_name}, tenho {age} anos, e sou maior de idade ? {of_legal_age}")