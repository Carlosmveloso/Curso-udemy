//* Operadores aritmétricos, de atribuição e incremento

// Aritmétricos

// '+' => Adição / Concatenação
const n1 = 10;
const n2 = 5;
console.log(n1 + n2);
// Diferente
const s1 = '10';
const s2 = '5';
console.log(s1 + s2);

// '-' => Subtração
console.log(n1 - n2);

// '*' => multiplicação
console.log(n1 * n2);

// '**' => Potenciação
console.log(n1 ** n2);

// '/' => Divisão
console.log(n1 / n2);

// '%' => Resto da divisão
console.log(n1 % n2);

  




